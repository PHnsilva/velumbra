patterns = UPPER | LOWER | EXTRA
glyphs, metrics, cmap = {}, {}, {}

def make_glyph(rows, accents=()):
    rows = rows.split('/')
    width = len(rows[0])
    cells = [(x, 6-y) for y, row in enumerate(rows) for x, bit in enumerate(row) if bit == '1']
    # Extra accent cells sit above the cap height; cedilla below the baseline.
    marks = {'\u0301': [(width//2,8),(width//2+1,9)], '\u0300':[(width//2,8),(width//2-1,9)],
             '\u0302':[(width//2-1,8),(width//2,9),(width//2+1,8)],
             '\u0303':[(0,8),(1,9),(2,9),(3,8),(4,9)],
             '\u0308':[(0,8),(width-1,8)], '\u0327':[(width//2,-1),(width//2+1,-2),(width//2,-3)]}
    for accent in accents: cells += marks.get(accent, [])
    pen = TTGlyphPen(None)
    for x,y in cells:
        x0,y0 = (x+1)*80, y*80
        pen.moveTo((x0,y0)); pen.lineTo((x0,y0+80)); pen.lineTo((x0+80,y0+80)); pen.lineTo((x0+80,y0)); pen.closePath()
    return pen.glyph(), ((width+2)*80, 80)

for char in [chr(i) for i in range(32,256)] + list('→×·☼☾✧⚖♞▥–—“”‘’…'):
    normalized = unicodedata.normalize('NFD', char)
    base = normalized[0]
    aliases = {'–':'-', '—':'-', '“':'"', '”':'"', '‘':"'", '’':"'", '\u00a0':' '}
    base = aliases.get(base,base)
    if char in patterns: base = char
    if base == ' ':
        glyph, metric = TTGlyphPen(None).glyph(), (240,0)
    elif base in patterns:
        glyph, metric = make_glyph(patterns[base], normalized[1:])
    else:
        continue
    name = 'uni%04X' % ord(char)
    glyphs[name], metrics[name], cmap[ord(char)] = glyph, metric, name
glyphs['.notdef'], metrics['.notdef'] = make_glyph('11111/10001/10101/10101/10101/10001/11111')
